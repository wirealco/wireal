// Writes THIRD_PARTY_NOTICES.txt: the licence and NOTICE texts of every
// package the web app, the MCP Worker and the runner are built from.
//
// It walks package.json `dependencies` transitively through node_modules the
// way Node resolves them, and for each package copies its `license` field and
// any LICENSE / LICENCE / COPYING / NOTICE files it ships. Dev dependencies
// are left out: they build and test the code but none of them ends up in what
// is shipped. Platform-specific optional binaries (packages that declare `os`
// or `cpu`) are left out too, so the file does not depend on the machine that
// generated it; their licences match the package that pulls them in. Peer
// dependencies are not followed: a peer the app ships is one of its own
// dependencies and is reached from there, and the rest (vite, typescript)
// are build tools. Build plugins listed as dependencies (the Tailwind Vite
// plugin) are still walked, which errs on the side of listing too much.
//
// Everything above the generated marker in the existing file is kept as it
// is: that part holds hand-written notices for code adapted into this
// repository rather than installed from npm.
//
//   npm run notices            rewrite the file
//   npm run notices -- --check exit 1 if the file is out of date
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "THIRD_PARTY_NOTICES.txt");
const marker =
  "==== Generated by scripts/third-party-notices.mjs (npm run notices); do not edit below. ====";
const rule = "-".repeat(78);

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

/** Node's lookup: node_modules beside `from`, then each parent directory. */
function locate(name, from) {
  let dir = from;
  for (;;) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return candidate;
    if (dir === root) return null;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

const seen = new Map();
const missing = [];

function visit(name, from, optional) {
  const dir = locate(name, from);
  if (!dir) {
    if (!optional) missing.push(name);
    return;
  }
  if (seen.has(dir)) return;
  const manifest = readJson(join(dir, "package.json"));
  if (optional && (manifest.os || manifest.cpu)) return;
  seen.set(dir, manifest);
  for (const dep of Object.keys(manifest.dependencies ?? {}))
    visit(dep, dir, false);
  for (const dep of Object.keys(manifest.optionalDependencies ?? {}))
    visit(dep, dir, true);
}

const own = readJson(join(root, "package.json"));
for (const dep of Object.keys(own.dependencies ?? {})) visit(dep, root, false);
if (missing.length)
  throw new Error(
    `not installed, run npm ci first: ${[...new Set(missing)].join(", ")}`,
  );

function licenseField(manifest) {
  const value = manifest.license ?? manifest.licenses;
  if (!value) return "UNKNOWN";
  if (typeof value === "string") return value;
  const list = Array.isArray(value) ? value : [value];
  return list.map((entry) => entry.type ?? String(entry)).join(" OR ");
}

function repository(manifest) {
  const repo = manifest.repository;
  const url = typeof repo === "string" ? repo : repo?.url;
  return url || manifest.homepage || "";
}

const legalFile = /^(licen[cs]e|copying|notice)([._-].*)?$/i;

function legalFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && legalFile.test(entry.name))
    .map((entry) => entry.name)
    .sort()
    .map((name) => ({
      name,
      text: readFileSync(join(dir, name), "utf8")
        .replace(/\r\n?/g, "\n")
        .trimEnd(),
    }));
}

const packages = [...seen.entries()]
  .map(([dir, manifest]) => ({ dir, manifest }))
  .sort(
    (a, b) =>
      a.manifest.name.localeCompare(b.manifest.name) ||
      a.manifest.version.localeCompare(b.manifest.version),
  );

// One entry per name@version, however many copies are installed.
const unique = new Map();
for (const entry of packages) {
  const key = `${entry.manifest.name}@${entry.manifest.version}`;
  if (!unique.has(key)) unique.set(key, entry);
}

const summary = [...unique.entries()].map(
  ([key, { manifest }]) => `  ${key}  ${licenseField(manifest)}`,
);

const sections = [...unique.entries()].map(([key, { dir, manifest }]) => {
  const lines = [rule, key, `License: ${licenseField(manifest)}`];
  const source = repository(manifest);
  if (source) lines.push(`Source: ${source}`);
  const files = legalFiles(dir);
  if (!files.length)
    lines.push(
      "",
      "The package ships no licence file; its package.json declares the licence above.",
    );
  for (const file of files) lines.push("", `--- ${file.name} ---`, file.text);
  return lines.join("\n");
});

const generated = [
  marker,
  "",
  "The packages below are installed from npm and bundled into, or run",
  "alongside, the Wireal web app, MCP Worker and runner. Each is used under",
  "its own licence, reproduced here with any NOTICE file it carries.",
  "",
  `${unique.size} packages:`,
  ...summary,
  "",
  ...sections,
  rule,
  "",
].join("\n");

const existing = existsSync(target) ? readFileSync(target, "utf8") : "";
const cut = existing.indexOf(marker);
const head = (cut === -1 ? existing : existing.slice(0, cut)).trimEnd();
const output = `${head ? `${head}\n\n` : ""}${generated}`;

if (process.argv.includes("--check")) {
  if (output !== existing) {
    console.error(
      "THIRD_PARTY_NOTICES.txt is out of date; run npm run notices.",
    );
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.txt is up to date.");
} else {
  writeFileSync(target, output);
  console.log(
    `third-party-notices: ${unique.size} packages written to THIRD_PARTY_NOTICES.txt`,
  );
}
